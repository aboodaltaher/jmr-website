// Collects every open "[TO CONFIRM: …]" marker into ONE file, TO_CONFIRM.md, so the
// owner can answer them in a single pass. A marker is resolved by replacing it in
// the source with the real fact (then re-run this script; it disappears from the list).
//
// Questions are grouped by FACT, not by page: identical markers (e.g. the same question on the
// English page, its Arabic twin and an FAQ) are listed once. Covers case studies
// (src/data/projects.ts), the long-form service pages and their Arabic twins
// (src/data/long-services*.ts) and the local community pages (src/data/communities.ts).
//
// Usage:  npm run to-confirm        (writes TO_CONFIRM.md at the repo root)
// Runs on Node >= 22 via built-in TypeScript type stripping (no build step).

import { writeFileSync } from "node:fs";

const load = (p: string) => import(new URL(p, import.meta.url).href);
const MARKER = /\[TO CONFIRM[^\]]*\]/g;

interface Hit {
  where: string;
  marker: string;
  context: string;
}

function walk(value: unknown, where: string, out: Hit[]): void {
  if (typeof value === "string") {
    for (const m of value.match(MARKER) ?? []) {
      const context = value.replace(MARKER, "…").replace(/\s+/g, " ").trim().slice(0, 110);
      out.push({ where, marker: m.replace(/^\[TO CONFIRM:?\s*/, "").replace(/\]$/, "").trim(), context });
    }
  } else if (Array.isArray(value)) {
    value.forEach((v, i) => walk(v, `${where}[${i}]`, out));
  } else if (value && typeof value === "object") {
    for (const [k, v] of Object.entries(value)) walk(v, where ? `${where}.${k}` : k, out);
  }
}

const hits = (v: unknown, where = ""): Hit[] => {
  const out: Hit[] = [];
  walk(v, where, out);
  return out;
};

const { projects } = await load("../src/data/projects.ts");
const { DUCTING, MEP, KITCHEN_EXHAUST } = await load("../src/data/long-services.ts");
const { DUCTING_AR, MEP_AR } = await load("../src/data/long-services-ar.ts");
const { communities } = await load("../src/data/communities.ts");

// One entry per QUESTION (the marker text). `where` lists every place that asks it.
interface Question {
  text: string;
  where: string[];
}
const norm = (t: string) => t.toLowerCase().replace(/\s+/g, " ").trim();

function group(items: { text: string; where: string }[]): Question[] {
  const map = new Map<string, Question>();
  for (const { text, where } of items) {
    const key = norm(text);
    const q = map.get(key) ?? { text, where: [] };
    if (!q.where.includes(where)) q.where.push(where);
    map.set(key, q);
  }
  return [...map.values()];
}

const lines: string[] = [];
let totalMarkers = 0;
let totalQuestions = 0;
const add = (s = "") => lines.push(s);

add("# TO_CONFIRM.md — open questions, grouped by fact");
add();
add("Generated by `npm run to-confirm`. Each question appears ONCE, even where several pages (or the Arabic");
add("twin) ask for the same fact. Write your answer after the arrow; once it is in the source the marker");
add("disappears from this list. Nothing on the live site shows a marker: production hides unanswered case-study");
add("sections, and pages that still have open markers return 404 in production until their publish switch");
add("(`src/data/new-pages.ts`) is on.");
add();

// ---- A. Company / service facts (answer once) -------------------------------
const company: { text: string; where: string }[] = [];
const collect = (label: string, data: unknown) => {
  for (const h of hits(data)) {
    totalMarkers++;
    company.push({ text: h.marker, where: label });
  }
};
collect("Ducting page (EN + AR)", DUCTING);
collect("Ducting page (EN + AR)", DUCTING_AR);
collect("MEP / HVAC-for-MEP page (EN + AR)", MEP);
collect("MEP / HVAC-for-MEP page (EN + AR)", MEP_AR);
collect("Kitchen exhaust page (unpublished)", KITCHEN_EXHAUST);

const companyQs = group(company);
// Blocking items first.
companyQs.sort((a, b) => Number(/blocking/i.test(b.text)) - Number(/blocking/i.test(a.text)));
totalQuestions += companyQs.length;
add(`## A. Company and service facts — answer once (${companyQs.length})`);
add();
companyQs.forEach((q, i) => {
  add(`${i + 1}. ${/blocking/i.test(q.text) ? "**BLOCKING** — " : ""}${q.text.replace(/^—?\s*BLOCKING:\s*/i, "")}`);
  add(`   - asked on: ${q.where.join("; ")}`);
  add(`   - answer → `);
});
add();

// ---- B. Case studies --------------------------------------------------------
const caseItems: { text: string; where: string }[] = [];
for (const p of projects) {
  for (const h of hits(p)) {
    if (h.where.startsWith("relatedServices")) continue;
    totalMarkers++;
    caseItems.push({ text: h.marker, where: `${p.name} (/projects/${p.slug})` });
  }
}
const caseQs = group(caseItems);
totalQuestions += caseQs.length;
add(`## B. Case studies — one answer per project for each question (${caseQs.length} questions × up to ${projects.length} projects)`);
add();
add("Leave a project's line blank to keep that section hidden for it. Client quotes only with the client's permission.");
add();
caseQs.forEach((q, i) => {
  add(`${i + 1}. ${q.text}`);
  for (const w of q.where) add(`   - ${w} → `);
});
add();

// ---- C. Community pages -----------------------------------------------------
const communityItems: { text: string; where: string }[] = [];
for (const c of communities) {
  for (const h of hits(c)) {
    totalMarkers++;
    communityItems.push({ text: h.marker, where: `${c.name} (/ac-maintenance/${c.slug})` });
  }
}
const communityQs = group(communityItems);
totalQuestions += communityQs.length;
add(`## C. Local community pages — noindex until answered (${communityQs.length} questions)`);
add();
communityQs.forEach((q, i) => {
  add(`${i + 1}. ${q.text}`);
  for (const w of q.where) add(`   - ${w} → `);
});
add();

add("---");
add(`${totalQuestions} questions to answer (covering ${totalMarkers} markers in the source).`);

writeFileSync(new URL("../TO_CONFIRM.md", import.meta.url), lines.join("\n") + "\n");
console.log(`Wrote TO_CONFIRM.md — ${totalQuestions} questions (${totalMarkers} markers)`);
