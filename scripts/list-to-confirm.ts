// Collects every open "[TO CONFIRM: …]" marker into ONE file, TO_CONFIRM.md, so the
// owner can answer them in a single pass. A marker is resolved by replacing it in
// the source with the real fact (then re-run this script; it disappears from the list).
//
// Covers: case studies (src/data/projects.ts), the new long-form service pages and
// their Arabic twins (src/data/long-services*.ts), and the local community pages
// (src/data/communities.ts).
//
// Usage:  npm run to-confirm        (writes TO_CONFIRM.md at the repo root)
// Runs on Node >= 22 via built-in TypeScript type stripping (no build step).

import { writeFileSync } from "node:fs";

const load = (p: string) => import(new URL(p, import.meta.url).href);
const MARKER = /\[TO CONFIRM[^\]]*\]/g;

interface Hit {
  where: string;
  marker: string;
  context: string;
}

function walk(value: unknown, where: string, out: Hit[]): void {
  if (typeof value === "string") {
    for (const m of value.match(MARKER) ?? []) {
      const context = value.replace(MARKER, "…").replace(/\s+/g, " ").trim().slice(0, 110);
      out.push({ where, marker: m.replace(/^\[TO CONFIRM:?\s*/, "").replace(/\]$/, "").trim(), context });
    }
  } else if (Array.isArray(value)) {
    value.forEach((v, i) => walk(v, `${where}[${i}]`, out));
  } else if (value && typeof value === "object") {
    for (const [k, v] of Object.entries(value)) walk(v, where ? `${where}.${k}` : k, out);
  }
}

const hits = (v: unknown, where = ""): Hit[] => {
  const out: Hit[] = [];
  walk(v, where, out);
  return out;
};

const { projects } = await load("../src/data/projects.ts");
const { DUCTING, MEP, KITCHEN_EXHAUST } = await load("../src/data/long-services.ts");
const { DUCTING_AR, MEP_AR } = await load("../src/data/long-services-ar.ts");
const { communities } = await load("../src/data/communities.ts");

const lines: string[] = [];
let total = 0;
const add = (s = "") => lines.push(s);

add("# TO_CONFIRM.md — every open [TO CONFIRM] marker");
add();
add("Generated by `npm run to-confirm`. Answer each item (write after the arrow), send it back, and the");
add("placeholder is replaced with the fact. Nothing on the live site shows a marker: case-study sections");
add("with no facts are hidden in production, and the new service pages stay noindex/unlinked until their");
add("publish switch (`src/data/new-pages.ts`) is flipped.");
add();

// ---- 1. Case studies -------------------------------------------------------
add("## 1. Case studies (13 projects)");
add();
add("Each project is missing the same kinds of fact. Answer per project; leave a line blank to keep that");
add("section hidden. Quotes are only used with the client's written permission.");
add();
for (const p of projects) {
  const hs = hits(p).filter((h) => !h.where.startsWith("relatedServices"));
  total += hs.length;
  add(`### ${p.name} — ${p.location.label}  \`/projects/${p.slug}\``);
  add();
  for (const h of hs) add(`- **${h.where}** — ${h.marker} → `);
  add();
}

// ---- 2. New service pages --------------------------------------------------
const section = (n: number, title: string, note: string, en: unknown, ar?: unknown) => {
  add(`## ${n}. ${title}`);
  add();
  add(note);
  add();
  const enHits = hits(en);
  const seen = new Set(enHits.map((h) => h.marker));
  total += enHits.length;
  enHits.forEach((h, i) => {
    add(`${i + 1}. ${h.marker}`);
    add(`   - in: “${h.context}”`);
    add(`   - answer → `);
  });
  if (ar) {
    const arHits = hits(ar);
    total += arHits.length;
    const extra = arHits.filter((h) => !seen.has(h.marker));
    add();
    add(`Arabic twin: ${arHits.length - extra.length} of ${arHits.length} markers repeat the questions above (answer once, applied to both).` +
      (extra.length ? ` ${extra.length} additional:` : ""));
    extra.forEach((h) => add(`- ${h.marker} → `));
  }
  add();
};

section(2, "AC ducting installation — `/ac-ducting-installation-dubai` (+ Arabic twin)",
  "Publish switch: `NEW_PAGES.ducting.published`.", DUCTING, DUCTING_AR);
section(3, "HVAC-led MEP contractor — `/mep-contractors-dubai` (+ Arabic twin)",
  "Publish switch: `NEW_PAGES.mep.published`. Note: no other trade is claimed until item 1 below is answered.", MEP, MEP_AR);
section(4, "Kitchen exhaust & hood cleaning — `/kitchen-exhaust-cleaning-dubai` (draft)",
  "Stays noindex, out of the sitemap and the menu, and unlinked until you decide to launch it. The first item BLOCKS launch.", KITCHEN_EXHAUST);

// ---- 5. Community pages ----------------------------------------------------
add("## 5. Local community pages — `/ac-maintenance/{slug}` (already in the repo, still noindex)");
add();
for (const c of communities) {
  const hs = hits(c);
  total += hs.length;
  add(`### ${c.name} (${hs.length})`);
  hs.forEach((h, i) => add(`${i + 1}. ${h.marker} → `));
  add();
}

add("---");
add(`Total open markers: **${total}**`);

writeFileSync(new URL("../TO_CONFIRM.md", import.meta.url), lines.join("\n") + "\n");
console.log(`Wrote TO_CONFIRM.md — ${total} open markers`);
