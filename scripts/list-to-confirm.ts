// Collects every open "[TO CONFIRM: …]" marker into ONE file, docs/open-questions.md, so the
// owner can answer them in a single pass. A marker is resolved by replacing it in
// the source with the real fact (then re-run this script; it disappears from the list).
//
// Grouped by PROJECT (case study / area page) as a tick-box checklist. Any facts still open on
// the long-form service pages (src/data/long-services*.ts) are listed once in their own section.
//
// Usage:  npm run to-confirm        (writes docs/open-questions.md)
// Runs on Node >= 22 via built-in TypeScript type stripping (no build step).

import { mkdirSync, writeFileSync } from "node:fs";

const load = (p: string) => import(new URL(p, import.meta.url).href);
const MARKER = /\[TO CONFIRM[^\]]*\]/g;

interface Hit {
  where: string;
  marker: string;
  context: string;
}

function walk(value: unknown, where: string, out: Hit[]): void {
  if (typeof value === "string") {
    for (const m of value.match(MARKER) ?? []) {
      const context = value.replace(MARKER, "…").replace(/\s+/g, " ").trim().slice(0, 110);
      out.push({ where, marker: m.replace(/^\[TO CONFIRM:?\s*/, "").replace(/\]$/, "").trim(), context });
    }
  } else if (Array.isArray(value)) {
    value.forEach((v, i) => walk(v, `${where}[${i}]`, out));
  } else if (value && typeof value === "object") {
    for (const [k, v] of Object.entries(value)) walk(v, where ? `${where}.${k}` : k, out);
  }
}

const hits = (v: unknown, where = ""): Hit[] => {
  const out: Hit[] = [];
  walk(v, where, out);
  return out;
};

const { projects } = await load("../src/data/projects.ts");
const { DUCTING, MEP, KITCHEN_EXHAUST } = await load("../src/data/long-services.ts");
const { DUCTING_AR, MEP_AR } = await load("../src/data/long-services-ar.ts");
const { communities } = await load("../src/data/communities.ts");

// Friendly label for a case-study field path.
const LABELS: [RegExp, string][] = [
  [/^clientType$/, "Client type"],
  [/^tonnage$/, "Installed capacity (TR)"],
  [/^challenge$/, "The main site or design challenge"],
  [/^decisions/, "Key design and installation decisions"],
  [/^results\[0\]/, "Commissioning — measured vs design airflow"],
  [/^results\[1\]/, "Commissioning — measured supply air temperature"],
  [/^results\[2\]/, "Commissioning — measured kW/TR"],
  [/^timeline\[0\]/, "Timeline — start date"],
  [/^timeline\[1\]/, "Timeline — handover date"],
  [/^timeline\[2\]/, "Timeline — programme length"],
  [/^quote\.text/, "Client quote (only with the client's written permission)"],
  [/^quote\.attribution/, "Quote attributed to (name / role)"],
];
const label = (where: string) => LABELS.find(([re]) => re.test(where))?.[1] ?? where;

const lines: string[] = [];
let total = 0;
const add = (s = "") => lines.push(s);

add("# Open questions — checklist grouped by project");
add();
add("Generated by `npm run to-confirm`. Write each answer after the arrow; once a fact is in the source its");
add("line disappears from this file. Leave a line blank to keep that section hidden — the live site never");
add("shows an unanswered placeholder (case-study sections are hidden; area pages return 404 until every");
add("question on them is answered).");
add();

// ---- Case studies ---------------------------------------------------------
add("## Case studies");
add();
for (const p of projects) {
  const hs = hits(p).filter((h: Hit) => !h.where.startsWith("relatedServices"));
  if (!hs.length) continue;
  total += hs.length;
  add(`### ${p.name} — ${p.location.label}`);
  add(`\`/projects/${p.slug}\` · ${hs.length} open`);
  add();
  for (const h of hs) add(`- [ ] ${label(h.where)} → `);
  add();
}

// ---- Area pages -------------------------------------------------------------
add("## Area pages (noindex; 404 in production until answered)");
add();
for (const c of communities) {
  const hs = hits(c);
  if (!hs.length) continue;
  total += hs.length;
  add(`### ${c.name}`);
  add(`\`/ac-maintenance/${c.slug}\` · ${hs.length} open`);
  add();
  for (const h of hs) add(`- [ ] ${h.marker.charAt(0).toUpperCase()}${h.marker.slice(1)} → `);
  add();
}

// ---- Service pages (only if anything is open) --------------------------------
const service = [
  ["Ducting page (EN + AR)", [DUCTING, DUCTING_AR]],
  ["HVAC for MEP projects page (EN + AR)", [MEP, MEP_AR]],
  ["Kitchen exhaust page", [KITCHEN_EXHAUST]],
] as const;
const seen = new Set<string>();
const serviceLines: string[] = [];
for (const [name, datas] of service) {
  for (const d of datas) {
    for (const h of hits(d)) {
      const key = name + h.marker;
      if (seen.has(key)) continue;
      seen.add(key);
      total++;
      serviceLines.push(`- [ ] ${name}: ${h.marker} → `);
    }
  }
}
add("## Service pages");
add();
if (serviceLines.length) lines.push(...serviceLines);
else add("None open — every fact on the ducting, HVAC-for-MEP and kitchen exhaust pages is confirmed.");
add();

add("---");
add(`${total} open answers.`);

mkdirSync(new URL("../docs/", import.meta.url), { recursive: true });
writeFileSync(new URL("../docs/open-questions.md", import.meta.url), lines.join("\n") + "\n");
console.log(`Wrote docs/open-questions.md — ${total} open answers`);
